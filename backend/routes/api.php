<?php

use App\Http\Controllers\Api\V1\AiMonitorController;
use App\Http\Controllers\Api\V1\ApplicationCallController;
use App\Http\Controllers\Api\V1\AuditEventController;
use App\Http\Controllers\Api\V1\AuthController;
use App\Http\Controllers\Api\V1\DashboardController;
use App\Http\Controllers\Api\V1\GlobalSearchController;
use App\Http\Controllers\Api\V1\KnowledgeSourceController;
use App\Http\Controllers\Api\V1\NotificationController;
use App\Http\Controllers\Api\V1\OnboardingController;
use App\Http\Controllers\Api\V1\OrganisationController;
use App\Http\Controllers\Api\V1\ProgrammeController;
use App\Http\Controllers\Api\V1\PublicAiController;
use App\Http\Controllers\Api\V1\PublicCatalogueController;
use App\Http\Controllers\Api\V1\RoleMatrixController;
use App\Http\Controllers\Api\V1\SystemSettingsController;
use App\Http\Controllers\Api\V1\UserManagementController;
use Illuminate\Support\Facades\Route;

Route::prefix('v1')->group(function () {
    Route::get('/catalogue/programmes', [PublicCatalogueController::class, 'index'])->middleware('throttle:120,1');
    Route::get('/catalogue/revision', [PublicCatalogueController::class, 'revision'])->middleware('throttle:120,1');
    Route::get('/catalogue/programmes/{programme}', [PublicCatalogueController::class, 'show'])->whereUuid('programme')->middleware('throttle:120,1');
    Route::get('/catalogue/assistant', [PublicAiController::class, 'configuration'])->middleware('throttle:120,1');
    Route::post('/catalogue/assistant/chat', [PublicAiController::class, 'chat'])->middleware('throttle:30,1');
    Route::post('/catalogue/assistant/feedback', [PublicAiController::class, 'feedback'])->middleware('throttle:60,1');
    Route::post('/auth/login', [AuthController::class, 'login'])->middleware('throttle:login');
    Route::post('/auth/password/forgot', [AuthController::class, 'forgotPassword'])->middleware('throttle:3,1');
    Route::post('/auth/password/reset', [AuthController::class, 'resetPassword'])->middleware('throttle:5,1');
    Route::post('/auth/onboarding/verify', [OnboardingController::class, 'verify'])->middleware('throttle:10,1');
    Route::post('/auth/onboarding/complete', [OnboardingController::class, 'complete'])->middleware('throttle:5,1');
    Route::post('/auth/onboarding/resend', [OnboardingController::class, 'resend'])->middleware('throttle:3,1');
    Route::middleware(['auth:sanctum', 'active.portal.account'])->group(function () {
        Route::get('/auth/me', [AuthController::class, 'me']);
        Route::get('/auth/profile', [AuthController::class, 'profile']);
        Route::post('/auth/profile', [AuthController::class, 'updateProfile'])->middleware('throttle:10,1');
        Route::put('/auth/password', [AuthController::class, 'updatePassword'])->middleware('throttle:5,1');
        Route::get('/auth/profile-photo', [AuthController::class, 'profilePhoto'])->middleware('throttle:60,1');
        Route::delete('/auth/profile-photo', [AuthController::class, 'deleteProfilePhoto'])->middleware('throttle:10,1');
        Route::post('/auth/reauthenticate', [AuthController::class, 'reauthenticate'])->middleware('throttle:10,1');
        Route::post('/auth/logout', [AuthController::class, 'logout']);
        Route::get('/dashboard', DashboardController::class);
        Route::get('/search', GlobalSearchController::class)->middleware('throttle:60,1');
        Route::get('/notifications', NotificationController::class)->middleware('throttle:60,1');
        Route::get('/system-settings/runtime', [SystemSettingsController::class, 'runtime']);
        Route::get('/programmes', [ProgrammeController::class, 'index']);
        Route::get('/programmes/options', [ProgrammeController::class, 'options']);
        Route::post('/programmes', [ProgrammeController::class, 'store']);
        Route::put('/programmes/{programme}', [ProgrammeController::class, 'update']);
        Route::post('/programmes/{programme}/action', [ProgrammeController::class, 'action']);
        Route::delete('/programmes/{programme}', [ProgrammeController::class, 'destroy']);
        Route::get('/application-calls', [ApplicationCallController::class, 'index']);
        Route::get('/application-calls/options', [ApplicationCallController::class, 'options']);
        Route::post('/application-calls', [ApplicationCallController::class, 'store']);
        Route::put('/application-calls/{applicationCall}', [ApplicationCallController::class, 'update']);
        Route::post('/application-calls/{applicationCall}/publish', [ApplicationCallController::class, 'publish']);
        Route::post('/application-calls/{applicationCall}/close', [ApplicationCallController::class, 'close']);
        Route::post('/application-calls/{applicationCall}/reopen', [ApplicationCallController::class, 'reopen']);
        Route::put('/application-calls/{applicationCall}/delegate', [ApplicationCallController::class, 'delegate']);
        Route::get('/admin/users', [UserManagementController::class, 'index']);
        Route::get('/admin/users/options', [UserManagementController::class, 'options']);
        Route::post('/admin/users', [UserManagementController::class, 'store']);
        Route::post('/admin/users/{user}/assignments', [UserManagementController::class, 'addAssignments']);
        Route::patch('/admin/users/{user}/status', [UserManagementController::class, 'status']);
        Route::post('/admin/users/{user}/reset-password', [UserManagementController::class, 'resetPassword']);
        Route::delete('/admin/users/{user}', [UserManagementController::class, 'destroy'])->middleware('throttle:5,1');
        Route::middleware('sysadmin')->group(function () {
            Route::get('/admin/organisation', [OrganisationController::class, 'index']);
            Route::get('/admin/affiliated-institutions', [OrganisationController::class, 'affiliates']);
            Route::post('/admin/organisation/faculties', [OrganisationController::class, 'storeFaculty']);
            Route::patch('/admin/organisation/faculties/{faculty}', [OrganisationController::class, 'updateFaculty']);
            Route::post('/admin/organisation/departments', [OrganisationController::class, 'storeDepartment']);
            Route::patch('/admin/organisation/departments/{department}', [OrganisationController::class, 'updateDepartment']);
            Route::get('/admin/system-settings', [SystemSettingsController::class, 'show']);
            Route::patch('/admin/system-settings', [SystemSettingsController::class, 'update']);
            Route::get('/admin/system-settings/secrets', [SystemSettingsController::class, 'secretStatuses'])->middleware('throttle:30,1');
            Route::put('/admin/system-settings/secrets/{key}', [SystemSettingsController::class, 'replaceSecret'])->middleware('throttle:5,1');
            Route::get('/admin/audit-events', AuditEventController::class);
            Route::get('/admin/role-matrix', RoleMatrixController::class);
            Route::match(['get'], '/admin/ai-monitor', [AiMonitorController::class, 'monitor']);
            Route::match(['get', 'post'], '/admin/ai-settings', [AiMonitorController::class, 'settings']);
            Route::get('/admin/knowledge-sources', [KnowledgeSourceController::class, 'index']);
            Route::post('/admin/knowledge-sources', [KnowledgeSourceController::class, 'store'])->middleware('throttle:10,1');
            Route::get('/admin/knowledge-sources/{knowledgeSource}', [KnowledgeSourceController::class, 'show']);
            Route::delete('/admin/knowledge-sources/{knowledgeSource}', [KnowledgeSourceController::class, 'destroy'])->middleware('throttle:5,1');
            Route::get('/admin/knowledge-sources/{knowledgeSource}/versions/{version}/content', [KnowledgeSourceController::class, 'reviewContent']);
            Route::patch('/admin/knowledge-sources/{knowledgeSource}/versions/{version}/findings/{finding}', [KnowledgeSourceController::class, 'resolveFinding'])->middleware('throttle:20,1');
            Route::post('/admin/knowledge-sources/{knowledgeSource}/versions/{version}/release', [KnowledgeSourceController::class, 'release'])->middleware('throttle:5,1');
        });
    });
});
